// PreToolUse (Edit|Write|MultiEdit|NotebookEdit|Read): protects generated and secret files.
import { basename } from 'node:path';
import { block, readEvent, repoPath } from './lib.mjs';

const event = await readEvent({ failClosed: true });
const tool = String(event?.tool_name ?? '');
const file = repoPath(event?.tool_input?.file_path ?? event?.tool_input?.notebook_path ?? '');
const name = basename(file);
const isEnvFile = /^\.env(\..+)?$/.test(name) && name !== '.env.example';

if (isEnvFile) {
  block(
    `Blocked: ${file} holds secrets. Do not ${tool === 'Read' ? 'read' : 'edit'} it; see .env.example for variable names.`,
  );
}

if (tool !== 'Read') {
  if (file.startsWith('apps/api/drizzle/')) {
    block(
      'Blocked: apps/api/drizzle/ is generated by drizzle-kit. Edit apps/api/src/db/schema.ts and run ' +
        '`npm run db:generate -- --name <change>`. Never hand-edit or rewrite an existing migration.',
    );
  }
  if (name === 'package-lock.json') {
    block('Blocked: package-lock.json is managed by npm. Use `npm install <pkg> -w <workspace>`.');
  }
}
process.exit(0);
